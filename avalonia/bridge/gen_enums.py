"""Generate C# option lists from the real Python enums so the Avalonia UI stays in sync."""
import sys
from enum import Enum
from pathlib import Path

from videocaptioner.core import entities as E
from videocaptioner.core.translate.types import TargetLanguage
from videocaptioner.core.utils.platform_utils import get_available_transcribe_models

enums = {
    "LLMService": E.LLMServiceEnum,
    "TranscribeModel": E.TranscribeModelEnum,
    "TranscribeOutputFormat": E.TranscribeOutputFormatEnum,
    "TranscribeLanguage": E.TranscribeLanguageEnum,
    "TranslatorService": E.TranslatorServiceEnum,
    "VadMethod": E.VadMethodEnum,
    "SubtitleLayout": E.SubtitleLayoutEnum,
    "SubtitleRenderMode": E.SubtitleRenderModeEnum,
    "VideoQuality": E.VideoQualityEnum,
    "WhisperModel": E.WhisperModelEnum,
    "FasterWhisperModel": E.FasterWhisperModelEnum,
    "TargetLanguage": TargetLanguage,
    "BatchTaskType": E.BatchTaskType,
    "BatchTaskStatus": E.BatchTaskStatus,
    "SupportedAudioFormats": E.SupportedAudioFormats,
    "SupportedVideoFormats": E.SupportedVideoFormats,
    "SupportedSubtitleFormats": E.SupportedSubtitleFormats,
}

def q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["// <auto-generated> by bridge/gen_enums.py from videocaptioner.core enums. Do not edit.",
       "namespace VideoCaptioner.Avalonia.Models;", "", "public static class Options", "{"]
for name, enum in enums.items():
    vals = ", ".join(q(m.value) for m in enum)
    out.append(f"    public static readonly string[] {name} = [{vals}];")
avail = ", ".join(q(m.value) for m in get_available_transcribe_models())
out.append(f"    public static readonly string[] AvailableTranscribeModel = [{avail}];")
out.append("}")
Path(sys.argv[1]).write_text("\n".join(out) + "\n", encoding="utf-8")
print("ok")
